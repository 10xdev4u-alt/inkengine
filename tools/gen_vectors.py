#!/usr/bin/env python3
"""Generate C++ LUT headers and bit-exact test vectors from loopkit.

Run from repo root with loopkit available at /tmp/build/loopkit/src:
    PYTHONPATH=/tmp/build/loopkit/src python3 tools/gen_vectors.py
"""
import struct
from pathlib import Path

import numpy as np

from loopkit.nvfp4 import (
    FP4_LEVELS,
    _E4M3_LUT,
    dequantize_mxfp8,
    dequantize_nvfp4,
    quantize_mxfp8,
    quantize_nvfp4,
)

ROOT = Path(__file__).resolve().parents[1]


def lit(v: float) -> str:
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s + "f"


def table(values) -> str:
    return "".join(f"    {lit(v)},\n" for v in values)


def write_vectors(name: str, n: int, blocks, scales, expected, block: int) -> None:
    out = bytearray(struct.pack("<I", n))
    for i in range(n):
        out += blocks[i].astype(np.uint8).tobytes()
        out += np.asarray(scales[i]).astype(np.uint8).tobytes()[:1]
        out += np.ascontiguousarray(expected[i]).tobytes()
    path = ROOT / "tests" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(bytes(out))
    print(f"wrote {path.name}: {len(out)} bytes, {n} blocks of {block}")


# 1) C++ LUT headers, both generated from the same loopkit E4M3 table.
lut = table(FP4_LEVELS)
e4 = table(_E4M3_LUT)
include = ROOT / "include"
include.mkdir(parents=True, exist_ok=True)
(include / "ink_lut.hpp").write_text(f"""// GENERATED by tools/gen_vectors.py — do not edit.
#pragma once
#include <array>
namespace ink {{
inline constexpr std::array<float, 16> kFp4Levels = {{
{lut}}};
inline constexpr std::array<float, 256> kE4M3 = {{
{e4}}};
}}  // namespace ink
""")

(include / "ink_mxfp8.hpp").write_text(f"""// GENERATED by tools/gen_vectors.py — do not edit.
#pragma once
#include <array>
#include <cmath>
#include <cstdint>
#include <span>
namespace ink {{
inline constexpr std::array<float, 256> kMxfp8E4M3 = {{
{e4}}};

// Bit-exact MXFP8 dequantization of one 32-element block.
// `codes` holds 32 E4M3 bytes; `exp_code` is an E8M0 byte encoding 2^(exp_code-127).
inline std::array<float, 32> dequant_mxfp8_block(std::span<const uint8_t, 32> codes,
                                                 uint8_t exp_code) {{
    const float scale = std::ldexp(1.0f, int(exp_code) - 127);
    std::array<float, 32> out{{}};
    for (int i = 0; i < 32; ++i) {{
        out[i] = kMxfp8E4M3[codes[i]] * scale;
    }}
    return out;
}}

}}  // namespace ink
""")

# 2) bit-exact vectors: 1000 blocks of 16 E2M1 codes + 1 E4M3 scale code + 16 f32.
rng = np.random.default_rng(20261123)
x = rng.standard_normal((1000, 16)).astype(np.float32)
t = quantize_nvfp4(x)
expected = dequantize_nvfp4(t).astype(np.float32)
write_vectors("vectors.bin", 1000, t.codes, t.scales, expected, 16)

# 3) bit-exact MXFP8 vectors: 500 blocks of 32 E4M3 codes + 1 E8M0 byte + 32 f32.
rng = np.random.default_rng(20261124)
x8 = rng.standard_normal((500, 32)).astype(np.float32)
x8[0, 0] = 0.0
x8[0, 1] = -0.0
x8[1, 2] = -0.0
x8[2, :] *= 1e-27  # exercise small/clamped E8M0 exponents
t8 = quantize_mxfp8(x8)
expected8 = dequantize_mxfp8(t8).astype(np.float32)
write_vectors("vectors_mxfp8.bin", 500, t8.codes, t8.scales, expected8, 32)
print("LUTs generated from loopkit")
