#!/usr/bin/env python3
"""Generate C++ LUT header and bit-exact test vectors from loopkit.

Run from repo root with loopkit available at /tmp/build/loopkit/src:
    PYTHONPATH=/tmp/build/loopkit/src python3 tools/gen_vectors.py
"""
import json
import struct
import sys
from pathlib import Path

import numpy as np

from loopkit.nvfp4 import FP4_LEVELS, _E4M3_LUT, dequantize_nvfp4, quantize_nvfp4

ROOT = Path(__file__).resolve().parents[1]

# 1) C++ LUT header
def lit(v: float) -> str:
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s + "f"

lut = "".join(f"    {lit(v)},\n" for v in FP4_LEVELS)
e4 = "".join(f"    {lit(v)},\n" for v in _E4M3_LUT)
(ROOT / "include/ink_lut.hpp").parent.mkdir(parents=True, exist_ok=True)
(ROOT / "include/ink_lut.hpp").write_text(f"""// GENERATED by tools/gen_vectors.py — do not edit.
#pragma once
#include <array>
namespace ink {{
inline constexpr std::array<float, 16> kFp4Levels = {{
{lut}}};
inline constexpr std::array<float, 256> kE4M3 = {{
{e4}}};
}}  // namespace ink
""")

# 2) bit-exact vectors: 1000 blocks of 16 codes + 1 E4M3 scale code + 16 expected f32
rng = np.random.default_rng(20261123)
x = rng.standard_normal((1000, 16)).astype(np.float32)
t = quantize_nvfp4(x)
expected = dequantize_nvfp4(t).astype(np.float32)
out = bytearray()
out += struct.pack("<I", 1000)
for i in range(1000):
    out += t.codes[i].astype(np.uint8).tobytes()
    out += np.asarray(t.scales[i]).astype(np.uint8).tobytes()[:1]
    out += np.ascontiguousarray(expected[i]).tobytes()
(ROOT / "tests/vectors.bin").parent.mkdir(parents=True, exist_ok=True)
(ROOT / "tests/vectors.bin").write_bytes(bytes(out))
print(f"wrote {len(out)} bytes, {1000} blocks; LUTs generated from loopkit")
